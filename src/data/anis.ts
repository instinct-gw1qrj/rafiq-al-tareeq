/** Stable "message of the day" so server and client render the same text for a given date. */
export function dailyIndex(length: number, d = new Date()) {
  const start = Date.UTC(d.getFullYear(), 0, 0);
  const day = Math.floor((Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) - start) / 86400000);
  return length ? day % length : 0;
}
